const switchLabel = (named, m, rai) => function (id) {
  const g = /^switch-([A-Za-z0-9]+)-(\d+)$/.exec(id);
  if (!g) return id;
  const i = Number(g[2]);
  if (g[1] === 'M') return m(i);
  if (g[1] === 'RAI') return rai(512 >> i);
  return (named[g[1]] && named[g[1]][i]) || id;
};

